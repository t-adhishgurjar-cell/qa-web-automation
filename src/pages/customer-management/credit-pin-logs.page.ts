import { Page, expect } from '@playwright/test';
import { BasePage } from '../base.page';

/**
 * Credit PIN Logs — `/Customer/CreditPinChangeLog`.
 *
 * Customer → Credit Pin Logs (`dbo.MenuMaster` MenuId 70). An audit list: every
 * credit-PIN change for the signed-in customer's branches, who made it, and
 * when it expires. The screen writes nothing, which is why it is the first of
 * the credit-PIN family to be automated.
 *
 * ── The same screen renders differently per role ──────────────────────────
 * Measured 28 September 2026 as both roles on 9200000000:
 *
 *   Customer Admin  #cplBranchLocationSelect   a dropdown, "All branches (12 locations)"
 *   Branch Admin    #cplBranchLocationReadonly a read-only input fixed to its own branch
 *
 * The control is *swapped*, not hidden — and the one that does not apply stays
 * in the DOM. A branch admin's page still contains #cplBranchLocationSelect,
 * empty and hidden, so `toBeAttached()` would pass for a control that role
 * cannot use. Everything here asserts visibility instead, and the two branch
 * controls are exposed separately rather than behind one accessor that would
 * paper over the difference.
 */
export class CreditPinLogsPage extends BasePage {
  static readonly URL = '/Customer/CreditPinChangeLog';

  /** The columns the grid renders, in order. */
  static readonly COLUMNS = [
    'S.No.',
    'Branch Customer ID',
    'Manager Name',
    'Manager Mobile',
    'Manager UID',
    'Parent UID',
    'PIN Changed On',
    'PIN Expiry At',
    'PIN Generated By',
    'Branch Location',
  ] as const;

  // ─── Filters ──────────────────────────────────────────────────────────────
  /** The customer, taken from the session. Displayed; the posted value is the hidden field. */
  readonly customerId = this.page.locator('#cplCustomerIdDisplay');
  readonly customerIdHidden = this.page.locator('#cplCustomerId');

  /** Customer Admin only. */
  readonly branchSelect = this.page.locator('#cplBranchLocationSelect');
  /** Branch Admin only — its own branch, not choosable. */
  readonly branchReadonly = this.page.locator('#cplBranchLocationReadonly');

  readonly mobileNumber = this.page.locator('#cplMobileNumber');
  readonly fromDate = this.page.locator('#cplFromDate');
  readonly toDate = this.page.locator('#cplToDate');
  readonly searchButton = this.page.locator('#cplSearchBtn');
  readonly resetButton = this.page.locator('#cplResetBtn');

  // ─── Grid ─────────────────────────────────────────────────────────────────
  readonly table = this.page.locator('#CreditPinChangeLogTbl');
  readonly rows = this.table.locator('tbody tr');
  readonly rowsPerPage = this.page.locator('#dt-length-0');
  readonly quickFilter = this.page.locator('#cplSearchFilter');
  readonly exportExcel = this.page.locator('#btnCplExcel');
  readonly exportPdf = this.page.locator('#btnCplPdf');

  constructor(page: Page) {
    super(page);
  }

  async navigate(): Promise<void> {
    await this.navigateTo(CreditPinLogsPage.URL);
    await this.settle();
  }

  /**
   * The page is loaded and showing its own content.
   *
   * The title is checked because this application answers an unentitled request
   * with HTTP 200 and an "Unauthorized Access" page — a status-code assertion
   * passes on a refusal. /Vehicle/EnableDisableProdTrans does exactly that for
   * both of these roles.
   */
  async assertLoaded(): Promise<void> {
    await expect(this.page, 'not on Credit PIN Logs').toHaveURL(/CreditPinChangeLog/i);
    await expect(this.page, 'the app refused this role rather than serving the screen')
      .not.toHaveTitle(/Unauthorized/i);
    await this.assertElementVisible(this.table, 'the Credit PIN Logs grid never rendered');
  }

  async assertColumns(): Promise<void> {
    const headers = await this.table.locator('thead th').allTextContents();
    expect(headers.map(h => h.trim())).toEqual([...CreditPinLogsPage.COLUMNS]);
  }

  // ─── Reading the grid ─────────────────────────────────────────────────────
  /**
   * The rendered rows as objects keyed by column name.
   *
   * DataTables leaves a placeholder row in place when a search returns nothing,
   * so a row count alone does not distinguish "one result" from "no results".
   * An empty grid is reported here as no rows at all.
   */
  async readRows(): Promise<Record<string, string>[]> {
    if (await this.isEmpty()) return [];

    return this.rows.evaluateAll((trs, columns) =>
      trs.map(tr => {
        const cells = Array.from(tr.querySelectorAll('td'))
          .map(td => (td.textContent || '').trim().replace(/\s+/g, ' '));
        return Object.fromEntries(columns.map((name, i) => [name, cells[i] ?? '']));
      }),
    [...CreditPinLogsPage.COLUMNS]);
  }

  /** True when the grid is showing DataTables' "no matching records" placeholder. */
  async isEmpty(): Promise<boolean> {
    const count = await this.rows.count();
    if (count === 0) return true;
    if (count > 1) return false;
    const cells = await this.rows.first().locator('td').count();
    return cells <= 1;
  }

  async column(name: typeof CreditPinLogsPage.COLUMNS[number]): Promise<string[]> {
    return (await this.readRows()).map(row => row[name]);
  }

  // ─── Filtering ────────────────────────────────────────────────────────────
  async search(): Promise<void> {
    await this.clickElement(this.searchButton);
    await this.settle();
  }

  async reset(): Promise<void> {
    await this.clickElement(this.resetButton);
    await this.settle();
  }

  async filterByMobile(mobile: string): Promise<void> {
    await this.fillInput(this.mobileNumber, mobile);
    await this.search();
  }

  /** Dates are typed as the input's own `yyyy-mm-dd`, not the grid's display format. */
  async filterByDateRange(from: string, to: string): Promise<void> {
    await this.fillInput(this.fromDate, from);
    await this.fillInput(this.toDate, to);
    await this.search();
  }

  async filterByBranch(label: string): Promise<void> {
    await this.branchSelect.selectOption({ label });
    await this.search();
  }

  /** Every branch the dropdown offers, excluding its "All branches" entry. */
  async branchOptions(): Promise<string[]> {
    const labels = await this.branchSelect.locator('option').allTextContents();
    return labels
      .map(label => label.trim())
      .filter(label => label && !/^all branches/i.test(label));
  }
}
